def crc32_mpeg2(data: bytes) -> int:
    table = []
    for i in range(256):
        c = i << 24
        for _ in range(8):
            c = ((c << 1) ^ 0x04C11DB7) & 0xFFFFFFFF if (c & 0x80000000) else (c << 1) & 0xFFFFFFFF
        table.append(c)
    crc = 0xFFFFFFFF
    for b in data:
        crc = ((crc << 8) & 0xFFFFFFFF) ^ table[((crc >> 24) ^ b) & 0xFF]
    return crc

def read_lang(path):
    with open(path, 'rb') as f:
        data = f.read()
    magic = struct.unpack('<I', data[0:4])[0]
    name = data[4:28].split(b'\x00')[0].decode('utf-8', errors='replace')
    count = struct.unpack('<I', data[28:32])[0]
    offsets = [struct.unpack('<I', data[32 + i*4 : 36 + i*4])[0] for i in range(count)]
    str_base = 32 + count * 4
    strings = []
    for off in offsets:
        end = data.find(b'\x00', str_base + off)
        s = data[str_base + off : end].decode('utf-8', errors='replace')
        strings.append(s)
    return magic, name, count, strings

def write_lang(path, lang_name: str, strings: list[str]):
    assert len(strings) == 212, f"Expected 212 strings, got {len(strings)}"
    name_buf = lang_name.encode('utf-8')[:23]
    name_buf = name_buf + b'\x00' * (24 - len(name_buf))
    offsets = []
    str_blob = bytearray()
    for s in strings:
        offsets.append(len(str_blob))
        str_blob.extend(s.encode('utf-8') + b'\x00')
    body = bytearray()
    body.extend(name_buf)
    body.extend(struct.pack('<I', len(strings)))
    for off in offsets:
        body.extend(struct.pack('<I', off))
    body.extend(str_blob)
    crc = crc32_mpeg2(body)
    full = struct.pack('<I', crc) + body
    with open(path, 'wb') as f:
        f.write(full)
    return crc, len(full)

